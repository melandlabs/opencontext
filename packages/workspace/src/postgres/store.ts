// ── helpers ───────────────────────────────────────────────────────────────

function currentUnixSeconds(): number {
	return Math.floor(Date.now() / 1000);
}

function sha256(value: string): string {
	return createHash("sha256").update(value).digest("hex");
}

/** A JSONB column reads back as an object; anything else is an empty record. */
function asRecord(value: unknown): Record<string, unknown> {
	if (value && typeof value === "object" && !Array.isArray(value)) {
		return value as Record<string, unknown>;
	}
	return {};
}

/**
 * Round-trip through JSON so the value is a plain object with plain
 * values — `isDeepStrictEqual` compares prototypes, and the front
 * matter may arrive as a class instance.
 */
function asPlainRecord(value: unknown): Record<string, unknown> {
	if (value === undefined || value === null) return {};
	return JSON.parse(JSON.stringify(value)) as Record<string, unknown>;
}

