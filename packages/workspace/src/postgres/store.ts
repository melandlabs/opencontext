	async softDeleteMissingResources(input: {
		workspace_id: string;
		presentKeys: Set<string>;
	}): Promise<Array<{ canonical_key: string }>> {
		await this.ensureInitialized();
		const rows = await this.pool.query<{ id: number; canonical_key: string; metadata: unknown }>(
			"SELECT id, canonical_key, metadata FROM workspace_resources WHERE workspace_id = $1",
			[input.workspace_id],
		);
		const missing: Array<{ canonical_key: string }> = [];
		const now = currentUnixSeconds();
		for (const row of rows.rows) {
			if (input.presentKeys.has(row.canonical_key)) continue;
			const meta = asRecord(row.metadata);
			if (meta.deleted_at) continue;
			meta.deleted_at = now;
			await this.pool.query(
				"UPDATE workspace_resources SET metadata = $1::jsonb, updated_at = $2 WHERE id = $3",
				[JSON.stringify(meta), now, row.id],
			);
			missing.push({ canonical_key: row.canonical_key });
		}
		return missing;
	}

