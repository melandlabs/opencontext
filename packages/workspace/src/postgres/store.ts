/**
 * `@melandlabs/workspace/postgres` — the Postgres-backed store.
 *
 * The SQLite store (`src/sqlite.ts`) and this one implement the same
 * contract (`src/store-types.ts`) and the same schema, so a host can
 * swap the backend without changing a line of application code:
 *
 *   - local / desktop → SQLite (a file, synchronous, no network),
 *   - serverless / cloud → Postgres (a shared database, asynchronous).
 *
 * The store is a thin SQL layer over `node-postgres`. The parts that
 * needed a decision:
 *
 *   - **Lexical search.** The SQLite backend mirrors its chunks into an
 *     FTS5 table and matches with `bm25()`. Here the derived index text
 *     lives in `workspace_chunks.index_text` and a generated `tsvector`
 *     column carries it; the query is built with `phraseto_tsquery`
 *     (see `./tokens`).
 *   - **Ranking.** `ts_rank()` replaces `bm25()`. Both are relevance
 *     scores in [0, 1] where higher is better, and the hybrid fusion
 *     ranks by position, not by magnitude.
 *   - **Semantic search.** `pgvector` replaces `sqlite-vec`: one
 *     `workspace_chunks_vec_d{N}` table per embedding width, queried
 *     with the cosine distance operator `<=>`. The extension is
 *     optional — without it the store keeps working and the API layer
 *     falls back to lexical search.
 *   - **Identifiers.** `INTEGER GENERATED BY DEFAULT AS IDENTITY`, so
 *     node-postgres hands them back as plain numbers. Timestamps are
 *     `BIGINT` (unix seconds) and come back as strings, so every mapper
 *     casts them with `Number()`.
 *   - **JSON.** `metadata` and `provenance` are `JSONB` rather than
 *     JSON-in-TEXT, so the store reads them back as objects and writes
 *     them with an explicit `::jsonb` cast.
 */

