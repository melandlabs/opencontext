	async indexResource(input: IndexResourceInput): Promise<IndexResourceResult> {
		await this.ensureInitialized();
		const { workspace_id, user_id, resource } = input;
		const now = currentUnixSeconds();
		const contentHash = sha256(resource.body);

		const client = await this.pool.connect();
		try {
			await client.query("BEGIN");
			const existingResult = await client.query<ResourceRow>(
				`SELECT id, user_id, current_version_id, title, resource_type, metadata
           FROM workspace_resources
           WHERE workspace_id = $1 AND canonical_key = $2
           FOR UPDATE`,
				[workspace_id, resource.canonical_key],
			);
			const existing = existingResult.rows[0];
			if (existing && existing.user_id !== user_id) {
				throw new Error("Workspace resource owner mismatch");
			}

			let prevVersion: VersionRow | undefined;
			if (existing?.current_version_id != null) {
				const versionResult = await client.query<VersionRow>(
					"SELECT id, resource_id, version_number, sha256, change_kind, size_bytes, parent_version_id, source_path, created_at, metadata FROM workspace_resource_versions WHERE id = $1",
					[existing.current_version_id],
				);
				prevVersion = versionResult.rows[0];
			}

			const previousFrontMatter = asPlainRecord(prevVersion?.metadata);
			const incomingFrontMatter =
				resource.front_matter === undefined ? previousFrontMatter : asPlainRecord(resource.front_matter);
			const sameRevision =
				prevVersion?.sha256 === contentHash &&
				isDeepStrictEqual(previousFrontMatter, incomingFrontMatter) &&
				existing?.title === resource.title &&
				existing?.resource_type === resource.resource_type &&
				prevVersion?.source_path === resource.absolute_path;
			if (
				input.expected_version_id !== undefined &&
				input.expected_version_id !== (existing?.current_version_id ?? null) &&
				(!sameRevision || asRecord(existing?.metadata).deleted_at)
			) {
				throw new Error("Workspace resource version conflict");
			}

			let resourceId: number;
			let currentVersionId: number | null = existing?.current_version_id ?? null;
			let changeKind: WorkspaceResourceVersion["change_kind"];

			if (!existing) {
				// Created rows stamp source_mtime into the same metadata
				// JSON that carries the front matter, so both ride the
				// resource row without an extra UPDATE.
				const createdMeta: Record<string, unknown> = { ...incomingFrontMatter };
				if (typeof resource.source_mtime === "number" && Number.isFinite(resource.source_mtime)) {
					createdMeta.source_mtime = resource.source_mtime;
				}
				const insert = await client.query<{ id: number }>(
					`INSERT INTO workspace_resources(
                        workspace_id, user_id, resource_type, canonical_key, title, storage_kind,
                        current_version_id, index_status, created_at, updated_at, metadata
                     ) VALUES ($1, $2, $3, $4, $5, $6, NULL, 'pending', $7, $8, $9::jsonb)
                     RETURNING id`,
					[
						workspace_id,
						user_id,
						resource.resource_type,
						resource.canonical_key,
						resource.title,
						"okf_local_dir",
						now,
						now,
						JSON.stringify(createdMeta),
					],
				);
				resourceId = insert.rows[0].id;
				changeKind = "created";
			} else {
				resourceId = existing.id;
				if (currentVersionId !== null && sameRevision) {
					changeKind = "unchanged";
					// A resource that was soft-deleted while its file was
					// away must become visible again even though the body
					// did not change.
					await this.clearSoftDeleteMarker(client, resourceId);
					await this.writeSourceMtimeMarker(client, resourceId, resource.source_mtime);
					await client.query("UPDATE workspace_resources SET updated_at = $1 WHERE id = $2", [
						now,
						resourceId,
					]);
					await client.query("COMMIT");
					return { resource_id: resourceId, version_id: currentVersionId, change_kind: changeKind };
				}
				changeKind = "modified";
			}

			const maxVersion = await client.query<{ max_version: string }>(
				"SELECT COALESCE(MAX(version_number), 0)::bigint AS max_version FROM workspace_resource_versions WHERE resource_id = $1",
				[resourceId],
			);
			const insertVersion = await client.query<{ id: number }>(
				`INSERT INTO workspace_resource_versions(
                    resource_id, version_number, sha256, change_kind, size_bytes,
                    parent_version_id, source_path, created_at, metadata
                 ) VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9::jsonb)
                 RETURNING id`,
				[
					resourceId,
					Number(maxVersion.rows[0]?.max_version ?? 0) + 1,
					contentHash,
					changeKind,
					resource.size_bytes,
					currentVersionId,
					resource.absolute_path,
					now,
					JSON.stringify(incomingFrontMatter),
				],
			);
			const versionId = insertVersion.rows[0].id;

			// Old chunks are dropped wholesale — the version chain keeps
			// the history, the chunk table only holds the current slice.
			await client.query("DELETE FROM workspace_chunks WHERE resource_id = $1", [resourceId]);

			const pieces = chunkTextByEstimatedTokens(resource.body, {
				maxTokens: RAW_MESSAGE_CHUNK_MAX_TOKENS,
				overlapTokens: RAW_MESSAGE_CHUNK_OVERLAP_TOKENS,
			});
			const chunkCount = pieces.length;
			const chunkParams = new Params();
			const valueRows: string[] = [];
			for (const piece of pieces) {
				const pieceHash = sha256(piece.content);
				const chunkId = `${workspace_id}:${resourceId}:${versionId}:chunk:${piece.chunkIndex}:${pieceHash.slice(0, 16)}`;
				valueRows.push(
					`(${[
						chunkParams.add(chunkId),
						chunkParams.add(resourceId),
						chunkParams.add(versionId),
						chunkParams.add(workspace_id),
						chunkParams.add(piece.chunkIndex),
						chunkParams.add(chunkCount),
						chunkParams.add(piece.startPosition),
						chunkParams.add(piece.endPosition),
						chunkParams.add(piece.content),
						chunkParams.add(pieceHash),
						chunkParams.add(workspaceIndexText(piece.content)),
					].join(", ")})`,
				);
			}
			if (valueRows.length > 0) {
				await client.query(
					`INSERT INTO workspace_chunks(
                        chunk_id, resource_id, version_id, workspace_id, chunk_index, chunk_count,
                        start_position, end_position, content, content_hash, index_text
                     ) VALUES ${valueRows.join(", ")}`,
					chunkParams.all(),
				);
			}

			// Replace source metadata while retaining store-owned lifecycle markers.
			const metadata = asRecord(existing?.metadata);
			for (const key of Object.keys(previousFrontMatter)) delete metadata[key];
			Object.assign(metadata, incomingFrontMatter);
			await client.query("UPDATE workspace_resources SET metadata = $1::jsonb WHERE id = $2", [
				JSON.stringify(metadata),
				resourceId,
			]);
			// Re-indexing a soft-deleted resource (the file came back with a
			// new body) restores it to list/search results.
			await this.clearSoftDeleteMarker(client, resourceId);
			await this.writeSourceMtimeMarker(client, resourceId, resource.source_mtime);

			await client.query(
				`UPDATE workspace_resources
             SET current_version_id = $1, index_status = 'pending', updated_at = $2, title = $3, resource_type = $4
             WHERE id = $5`,
				[versionId, now, resource.title, resource.resource_type, resourceId],
			);

			await client.query("COMMIT");
			currentVersionId = versionId;
			return { resource_id: resourceId, version_id: versionId, change_kind: changeKind };
		} catch (error) {
			await client.query("ROLLBACK").catch(() => undefined);
			throw error;
		} finally {
			client.release();
		}
	}

