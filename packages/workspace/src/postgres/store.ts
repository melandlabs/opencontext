	async writeChunkEmbeddings(
		entries: Array<{ chunkId: string; embedding: number[] }>,
		model: string,
		dimensions: number,
	): Promise<void> {
		if (entries.length === 0) return;
		await this.ensureInitialized();
		const tableName = workspaceVectorTableName(dimensions);
		const hasVectorTable = await this.vectorTableExists(tableName);
		const now = currentUnixSeconds();
		const client = await this.pool.connect();
		try {
			await client.query("BEGIN");
			// The vector rows carry the workspace id so the semantic
			// search can filter on it without joining the chunk table.
			const workspaceIdByChunk = new Map<string, string>();
			if (hasVectorTable) {
				const chunkRows = await client.query<{ chunk_id: string; workspace_id: string }>(
					"SELECT chunk_id, workspace_id FROM workspace_chunks WHERE chunk_id = ANY($1::text[])",
					[entries.map((entry) => entry.chunkId)],
				);
				for (const row of chunkRows.rows) {
					workspaceIdByChunk.set(row.chunk_id, row.workspace_id);
				}
			}
			for (const entry of entries) {
				await client.query(
					`UPDATE workspace_chunks
               SET embedding = $1::real[], embedding_model = $2, embedding_dimensions = $3, embedding_updated_at = $4
               WHERE chunk_id = $5`,
					[toRealArrayLiteral(entry.embedding), model, dimensions, now, entry.chunkId],
				);
				if (hasVectorTable) {
					await client.query(
						`INSERT INTO ${tableName}(chunk_id, workspace_id, embedding)
               VALUES ($1, $2, $3::vector)
               ON CONFLICT (chunk_id) DO UPDATE SET embedding = EXCLUDED.embedding`,
						[entry.chunkId, workspaceIdByChunk.get(entry.chunkId) ?? "", toVectorLiteral(entry.embedding)],
					);
				}
			}
			await client.query("COMMIT");
		} catch (error) {
			await client.query("ROLLBACK").catch(() => undefined);
			throw error;
		} finally {
			client.release();
		}
	}

